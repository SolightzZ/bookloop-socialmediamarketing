const addCommunityReviews = (book: Book, bookIndex: number): Book => {
  const start = (bookIndex * 2) % communityReviewPool.length;
  const reviews = [0, 1, 2].map((offset) => {
    const review = communityReviewPool[(start + offset) % communityReviewPool.length];
    return { ...review, id: `${book.id}-${review.id}` };
  });

  return { ...book, reviews };
};

